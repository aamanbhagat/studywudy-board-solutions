#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { DatabaseSync } from "node:sqlite";

import {
  isQuestionRenderedDiagramAvailable,
  isQuestionRowIndexable,
} from "../answer-completeness.mjs";
import { CORPUS_QUALITY_DUPLICATE_CHOICE_ROW_IDS } from "../corpus-quality-manifest.mjs";
import { corpusQuestionIndexEligible } from "../corpus-quality.mjs";
import {
  isBookQuarantined,
  languageForBookId,
} from "../multilingual-text-quality.mjs";
import { PHASE4_GATE_MANIFEST } from "../phase4-publish-manifest.mjs";
import { normalizedQuestionType } from "../question-classification.mjs";
import { getQuestionUrl, questionRecordFromCatalogRow } from "../question-routes.mjs";

export const NIGHTLY_QUALITY_SAMPLE_POLICY = "rotating-stratified-v1-public-gate";

const root = resolve(import.meta.dirname, "..");
const databasePath = resolve(root, "../data/d1/studywudy-content.sqlite3");
const outputPath = resolve(root, "nightly-quality-sample-manifest.mjs");
const minimumCategorySize = 100;
const derivationPrompt = /\b(?:derive|derivation|prove|show\s+that|deduce)\b/iu;

function stableEntry(row) {
  const language = languageForBookId(row.book_id);
  return Object.freeze({
    pathname: getQuestionUrl(questionRecordFromCatalogRow(row)),
    questionId: row.question_id,
    bookId: row.book_id,
    type: normalizedQuestionType(row),
    language: language || "en-IN",
  });
}

function buildManifest() {
  const database = new DatabaseSync(databasePath, { readOnly: true });
  try {
    const rows = database.prepare(`SELECT q.row_id, q.book_id, q.chapter_slug, q.question_id,
      q.type, q.prompt_text, b.board_slug, b.grade_slug, b.subject_slug, b.slug AS book_slug
      FROM catalog_questions q JOIN catalog_books b ON b.id = q.book_id ORDER BY q.row_id`).all();
    const categories = { mcq: [], numerical: [], diagram: [], derivation: [], multilingual: [] };
    const entries = {};

    for (const row of rows) {
      const rowId = Number(row.row_id);
      if (!isQuestionRowIndexable(PHASE4_GATE_MANIFEST, rowId)) continue;
      if (!corpusQuestionIndexEligible({
        questionId: row.question_id,
        rowId,
        duplicateRowIds: CORPUS_QUALITY_DUPLICATE_CHOICE_ROW_IDS,
      })) continue;
      if (isBookQuarantined(row.book_id)) continue;

      const type = normalizedQuestionType(row);
      const language = languageForBookId(row.book_id);
      const memberships = [];
      if (["mcq_single", "mcq_multi"].includes(type)) memberships.push("mcq");
      if (type === "numerical") memberships.push("numerical");
      if (isQuestionRenderedDiagramAvailable(PHASE4_GATE_MANIFEST, rowId)) memberships.push("diagram");
      if (type === "detailed" && derivationPrompt.test(String(row.prompt_text || ""))) memberships.push("derivation");
      if (language) memberships.push("multilingual");
      if (!memberships.length) continue;

      entries[rowId] = stableEntry(row);
      for (const category of memberships) categories[category].push(rowId);
    }

    for (const [category, rowIds] of Object.entries(categories)) {
      if (rowIds.length < minimumCategorySize) {
        throw new Error(`${category} has only ${rowIds.length} publicly eligible candidates; ${minimumCategorySize} are required`);
      }
    }

    const digest = createHash("sha256")
      .update(JSON.stringify({ entries, categories }))
      .digest("hex");
    return Object.freeze({
      policyVersion: NIGHTLY_QUALITY_SAMPLE_POLICY,
      publishingGateVersion: PHASE4_GATE_MANIFEST.policyVersion,
      generatedFromReview: PHASE4_GATE_MANIFEST.reviewedAt,
      digest,
      entries,
      categories,
    });
  } finally {
    database.close();
  }
}

function manifestSource(manifest) {
  return `// Generated by scripts/build-nightly-quality-sample.mjs. Do not edit by hand.\n`
    + `const rawManifest = ${JSON.stringify(manifest)};\n`
    + `export const NIGHTLY_QUALITY_SAMPLE_MANIFEST = Object.freeze({ ...rawManifest, entries: Object.freeze(rawManifest.entries), categories: Object.freeze(rawManifest.categories) });\n`;
}

const mode = process.argv[2];
const manifest = buildManifest();
const source = manifestSource(manifest);
if (mode === "--write") {
  writeFileSync(outputPath, source);
  console.log(`Wrote ${outputPath} with ${Object.keys(manifest.entries).length} candidates: ${JSON.stringify(Object.fromEntries(Object.entries(manifest.categories).map(([key, values]) => [key, values.length])))}`);
} else if (mode === "--check") {
  if (readFileSync(outputPath, "utf8") !== source) {
    throw new Error("nightly-quality-sample-manifest.mjs is stale; run pnpm build:nightly-quality-sample");
  }
  console.log(`PASS: rotating nightly pools match ${manifest.digest}`);
} else {
  throw new Error("Usage: node scripts/build-nightly-quality-sample.mjs --write|--check");
}
